#!/usr/bin/env bash
# LAPTOP. Writes .local/ssh_config from the Terraform outputs.
# Everything else then uses:  ssh -F .local/ssh_config <prefix>-bastion | <prefix>-k3s
#
# Why a separate config file: we never touch ~/.ssh/config on a laptop that
# isn't ours, and deleting .local/ removes every trace.
#
# Why ProxyCommand "ssh -W" (= ProxyJump): the bastion only relays an encrypted
# TCP stream. The private key never leaves the laptop and no agent is forwarded,
# so a compromised bastion cannot reuse our identity.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
need terraform; need ssh

mkdir -p "${LOCAL_DIR}"; chmod 700 "${LOCAL_DIR}"
CFG="$(ssh_cfg)"
KNOWN="${LOCAL_DIR}/known_hosts"
: > "${KNOWN}"   # host keys are per VM: start clean, so a re-created VM is not refused as "changed"

PREFIX="$(tf_out name_prefix)"
PROJECT="$(tf_out project_id)"
ZONE="$(tf_out zone)"
BASTION_NAME="$(tf_out bastion_name)"
BASTION_IP="$(tf_out bastion_public_ip || true)"
K3S_IP="$(tf_out k3s_internal_ip)"
KEY="${SSH_KEY:-$HOME/.ssh/airis_fde}"

if [ "$(tf_out enable_oslogin)" = "true" ]; then
  need gcloud
  log "OS Login mode: registering the public key with your Google identity (8h TTL)"
  gcloud config set project "${PROJECT}" >/dev/null 2>&1
  # Username from the import response (project-scoped). External accounts get an ext_ prefix
  # and need roles/compute.osLoginExternalUser (org) + roles/compute.osAdminLogin (project).
  SSH_USER="${OSLOGIN_USER:-$(gcloud compute os-login ssh-keys add --key-file="${KEY}.pub" --ttl=8h \
    --format='value(loginProfile.posixAccounts[0].username)')}"
else
  SSH_USER="$(tf_out ssh_user)"
fi
[ -n "$SSH_USER" ] || die "could not determine SSH user"
[ -f "$KEY" ] || die "private key $KEY not found"
chmod 600 "$KEY"  # ssh refuses keys readable by others ("UNPROTECTED PRIVATE KEY FILE")

if [ -n "$BASTION_IP" ]; then
  BASTION_HOST_LINES="  HostName ${BASTION_IP}"
  log "public-bastion mode: ${BASTION_IP}"
else
  need gcloud
  BASTION_HOST_LINES="  HostName ${BASTION_NAME}
  ProxyCommand gcloud compute start-iap-tunnel ${BASTION_NAME} 22 --listen-on-stdin --zone ${ZONE} --project ${PROJECT} --verbosity=error"
  log "IAP mode: bastion has no public IP, SSH goes through Google IAP"
fi

cat > "$CFG" <<EOF
# Generated by scripts/10-ssh-config.sh - do not edit by hand.
Host ${PREFIX}-bastion
${BASTION_HOST_LINES}
  User ${SSH_USER}
  IdentityFile "${KEY}"
  IdentitiesOnly yes
  ForwardAgent no
  StrictHostKeyChecking accept-new
  UserKnownHostsFile "${KNOWN}"
  ServerAliveInterval 30

Host ${PREFIX}-k3s
  HostName ${K3S_IP}
  User ${SSH_USER}
  IdentityFile "${KEY}"
  IdentitiesOnly yes
  ForwardAgent no
  StrictHostKeyChecking accept-new
  UserKnownHostsFile "${KNOWN}"
  ProxyCommand ssh -F "${CFG}" -W %h:%p ${PREFIX}-bastion
  ServerAliveInterval 30
EOF
chmod 600 "$CFG"
ok "wrote $CFG"

log "Testing: laptop -> bastion"
for i in $(seq 1 20); do
  if ssh -F "$CFG" -o ConnectTimeout=8 "${PREFIX}-bastion" true 2>/dev/null; then ok "bastion reachable"; break; fi
  if [ "$i" -eq 20 ]; then
    ssh -F "$CFG" -o ConnectTimeout=8 "${PREFIX}-bastion" true || true   # show the real error
    die "bastion not reachable - check allowed_ssh_cidrs vs your egress IP (site may also block outbound 22: use IAP mode), and that the VM is RUNNING"
  fi
  sleep 6
done

log "Testing: laptop -> bastion -> k3s node"
if ssh -F "$CFG" -o ConnectTimeout=10 "${PREFIX}-k3s" true 2>/dev/null; then ok "k3s node reachable through the bastion"
else warn "k3s node not reachable yet (still booting?) - retry: ssh -F $CFG ${PREFIX}-k3s"; fi

echo
echo "  ssh -F $CFG ${PREFIX}-bastion"
echo "  ssh -F $CFG ${PREFIX}-k3s"
